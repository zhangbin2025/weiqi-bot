import { describe, it, expect } from 'vitest';
import { normalizeName } from '../NameNormalize';

describe('normalizeName', () => {
  it('修用户报的薑→姜（手写窄表漏掉的那个）', () => {
    expect(normalizeName('薑小明')).toBe('姜小明');
  });

  it('修此前实测到的 4 个繁体名', () => {
    expect(normalizeName('於富泷')).toBe('于富泷');
    expect(normalizeName('黃泽楠')).toBe('黄泽楠');
    expect(normalizeName('呂克奇')).toBe('吕克奇');
    expect(normalizeName('王俊傑')).toBe('王俊杰');
  });

  it('常见姓氏全覆盖（非手写表，来自 OpenCC 全量字典）', () => {
    const cases: Array<[string, string]> = [
      ['陳', '陈'], ['鄭', '郑'], ['張', '张'], ['劉', '刘'], ['楊', '杨'],
      ['趙', '赵'], ['馮', '冯'], ['蔣', '蒋'], ['韓', '韩'], ['蘇', '苏'],
      ['盧', '卢'], ['賈', '贾'], ['鄒', '邹'], ['喬', '乔'], ['賴', '赖'],
      ['龍', '龙'], ['葉', '叶'], ['歐', '欧'], ['簡', '简'], ['羅', '罗'],
      ['謝', '谢'], ['蕭', '萧'], ['鄧', '邓'], ['許', '许'], ['鍾', '钟'],
      ['譚', '谭'], ['陸', '陆'], ['閻', '阎'], ['賀', '贺'], ['顧', '顾'],
      ['龔', '龚'], ['萬', '万'], ['嚴', '严'], ['湯', '汤'], ['衛', '卫'],
      ['華', '华'], ['單', '单'], ['關', '关'], ['竇', '窦'], ['邊', '边'],
      ['寧', '宁'], ['師', '师'], ['應', '应'], ['莊', '庄'], ['塗', '涂'],
      ['費', '费'], ['龐', '庞'], ['欒', '栾'], ['樂', '乐'], ['時', '时'],
      ['閔', '闵'], ['雲', '云'], ['韋', '韦'], ['風', '风'], ['馬', '马'],
      ['駱', '骆'], ['魯', '鲁'], ['鮑', '鲍'], ['鴻', '鸿'], ['薑', '姜'],
    ];
    for (const [t, s] of cases) {
      expect(normalizeName(t), `${t} 应转为 ${s}`).toBe(s);
    }
  });

  it('简体姓名不得被误改（防全量字典过度转换）', () => {
    // 全量字典的风险：某些简体字本身也是别的字的繁体（如 余/云/谷/后/范/卜）。
    // 若字典把「简体字」当成 key，就会把本已正确的名字改错 —— 这里守住。
    const keep = [
      '陈智洋', '刘伯逸', '余玥宇', '王未廷', '朱语诺', '李郭宇',
      '杨泽诚', '丁彦豪', '纪博诚', '沈开元', '徐一尘', '黄陆轩',
      '于富泷', '姜小明', '吕克奇', '王俊杰', '黄泽楠',
      '余胜', '云蛇', '谷雨', '后天', '范晓妍', '卜算子',
    ];
    for (const n of keep) {
      expect(normalizeName(n), `${n} 是简体，不应被改`).toBe(n);
    }
  });

  it('幂等：重复归一化结果不变', () => {
    for (const n of ['於富泷', '薑小明', '王俊傑', '陈智洋']) {
      const once = normalizeName(n);
      expect(normalizeName(once), `${n} 二次归一化应稳定`).toBe(once);
    }
  });

  it('空串与非姓名文本安全', () => {
    expect(normalizeName('')).toBe('');
    expect(normalizeName('2026年全国围棋行业职工大赛')).toBe('2026年全国围棋行业职工大赛');
    expect(normalizeName('宁波市总工会代表队')).toBe('宁波市总工会代表队');
  });
});
