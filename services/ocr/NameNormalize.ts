/** 合并后的繁→简映射 */
const T2S: Record<string, string> = { ...SURNAME_T2S, ...GIVEN_T2S };

/**
 * 把姓名中的繁体字归一化成简体
 *
 * 逐字映射，命中才替换；已经是简体或不在表内的字原样保留。
 *
 * @param name 原始姓名（可能含繁体）
 * @returns 归一化后的姓名
 */
export function normalizeName(name: string): string {
  if (!name) return name;

  let out = '';
  let changed = false;
  for (const ch of name) {
    const s = T2S[ch];
    if (s === undefined) {
      out += ch;
    } else {
      out += s;
      changed = true;
    }
  }

  // 记录实际发生的归一化，便于追溯「这个名字原本被识别成什么」
  ocrDebugLazy('name.normalize', () => (changed ? { 原: name, 改后: out } : null));

  return changed ? out : name;
}
