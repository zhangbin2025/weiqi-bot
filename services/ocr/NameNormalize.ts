/**
 * 姓名繁简归一化
 * @module services/ocr/NameNormalize
 *
 * ## 为什么需要
 *
 * PP-OCRv5 偶尔会把简体字识别成形近的繁体字，且**不是「两个都识别了选错」**——
 * 实测 0.png 的 1300 个原始块里，繁体块**不存在对应的简体块**：
 *
 * | 原始块 | y | 置信度 |
 * |---|---|---|
 * | `於富泷` | 1076 | 0.87 |
 * | `黃泽楠` | 448 | 0.84 |
 * | `呂克奇` | 3036 | 0.97 |
 * | `王俊傑` | 5025 | 0.83 |
 *
 * 置信度普遍偏低（0.83~0.97），说明是形近误判而非真繁体输入。
 * 用户明确反馈「于显示了繁体的於」，故在出口做归一化。
 *
 * ## 为什么不用 OpenCC
 *
 * `opencc-js` 做完整繁简转换更全，但要引入额外依赖。
 * OCR bundle 已经 11MB+，为一个「偶尔出现的形近误判」再堆体积不划算。
 * 且完整转换会引入「一简对多繁」的歧义（如 發/髮 → 发），人名场景并不需要。
 *
 * 这里用**窄表**：只收姓氏与名字常用字的繁体形式，逐字映射，无歧义。
 *
 * ## 扩展方式
 *
 * 遇到新的繁体输出，在 `__WEIQI_OCR_ITEMS__` 里确认是形近误判后，
 * 往对应分组补一行即可。分区只为可读性，合并后统一使用。
 */

